"""Alembic migration environment.

Importing `app.main` imports every router, and every router imports its
models, so `Base.metadata` holds the complete schema before autogenerate
compares it with the database.

SQLite cannot alter most columns in place, so migrations run in batch mode:
Alembic rebuilds the table instead, and the same migration also runs on
PostgreSQL.

Generated by Blacksmith. You own this file — customize as needed.
"""

from logging.config import fileConfig

from alembic import context

import app.main  # noqa: F401  (registers every model with Base.metadata)
from app.config import settings
from app.db import Base, engine

config = context.config

if config.config_file_name is not None:
    # Keep the app's own loggers (and pytest's) working when migrations run
    # inside the test session.
    fileConfig(config.config_file_name, disable_existing_loggers=False)

target_metadata = Base.metadata


def run_migrations_offline() -> None:
    """Emit SQL to stdout instead of running it (`alembic upgrade --sql`)."""
    context.configure(
        url=settings.database_url,
        target_metadata=target_metadata,
        literal_binds=True,
        render_as_batch=True,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    with engine.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            render_as_batch=True,
        )
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
