"""Page-number pagination matching DRF's `PageNumberPagination`.

The generated React hooks read `count` / `next` / `previous` / `results`
straight off a list response, so the envelope and the absolute page URLs both
match what a Django backend returns.

Generated by Blacksmith. You own this file — customize as needed.
"""

from starlette.datastructures import URL

PAGE_SIZE = 20


def page_offset(page: int, page_size: int = PAGE_SIZE) -> int:
    """Rows to skip to reach `page` (1-based)."""
    return (max(page, 1) - 1) * page_size


def page_url(url: URL, page: int) -> str:
    """`url` with `page` set. DRF omits `page=1`: page one is the bare URL."""
    if page == 1:
        return str(url.remove_query_params("page"))
    return str(url.include_query_params(page=page))


def page_links(
    url: URL, page: int, count: int, page_size: int = PAGE_SIZE
) -> tuple[str | None, str | None]:
    """The `next` and `previous` links for `page` of `count` rows."""
    last_page = max(1, -(-count // page_size))
    next_link = page_url(url, page + 1) if page < last_page else None
    previous_link = page_url(url, page - 1) if page > 1 else None
    return next_link, previous_link
