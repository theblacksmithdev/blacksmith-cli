"""Request validation errors in Django REST Framework's shape.

FastAPI answers an invalid body with a 422 and a list of error objects. The
generated frontend reads DRF's shape instead, a 400 mapping each field to its
messages, so forms can show an error under the field it belongs to:

    {"title": ["This field is required."]}

The OpenAPI document follows suit and drops FastAPI's automatic 422
responses, as drf-spectacular documents no error bodies. Left in, they would
type every generated React hook's error as `HttpValidationError`, a shape this
API never sends.

Generated by Blacksmith. You own this file — customize as needed.
"""

from fastapi import FastAPI, Request, status
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse

REQUIRED_MESSAGE = "This field is required."
BLANK_MESSAGE = "This field may not be blank."
FASTAPI_ERROR_SCHEMAS = ("HTTPValidationError", "ValidationError")


def error_field(loc: tuple) -> str:
    """`("body", "title")` → `title`. An error on the whole body has no field."""
    return ".".join(str(part) for part in loc[1:]) or "non_field_errors"


def error_message(error: dict) -> str:
    """DRF's wording for the errors every form hits; Pydantic's for the rest."""
    if error["type"] == "missing":
        return REQUIRED_MESSAGE
    if error["type"] == "string_too_short" and error.get("ctx", {}).get("min_length") == 1:
        return BLANK_MESSAGE
    return error["msg"]


async def validation_error_handler(
    request: Request, exc: RequestValidationError
) -> JSONResponse:
    errors: dict[str, list[str]] = {}
    for error in exc.errors():
        errors.setdefault(error_field(error["loc"]), []).append(error_message(error))
    return JSONResponse(status_code=status.HTTP_400_BAD_REQUEST, content=errors)


def drop_validation_responses(schema: dict) -> dict:
    """Remove the 422 responses and the schemas only they referenced."""
    for operations in schema.get("paths", {}).values():
        for operation in operations.values():
            operation.get("responses", {}).pop("422", None)
    components = schema.get("components", {}).get("schemas", {})
    for name in FASTAPI_ERROR_SCHEMAS:
        components.pop(name, None)
    return schema


def use_drf_errors(app: FastAPI) -> None:
    """Answer and document validation errors the way DRF does."""
    app.add_exception_handler(RequestValidationError, validation_error_handler)

    build_openapi = app.openapi

    def openapi() -> dict:
        if app.openapi_schema is None:
            app.openapi_schema = drop_validation_responses(build_openapi())
        return app.openapi_schema

    app.openapi = openapi
