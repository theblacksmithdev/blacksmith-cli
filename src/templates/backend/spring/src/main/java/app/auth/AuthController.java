package app.auth;

import app.auth.dto.ChangePasswordRequest;
import app.auth.dto.ForgotPasswordRequest;
import app.auth.dto.LoginRequest;
import app.auth.dto.LogoutRequest;
import app.auth.dto.PatchedUserRequest;
import app.auth.dto.RefreshRequest;
import app.auth.dto.RegisterRequest;
import app.auth.dto.ResetPasswordRequest;
import app.auth.dto.TokenPair;
import app.auth.dto.UserResponse;
import app.errors.Detail;
import app.users.User;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import org.springframework.http.HttpStatus;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PatchMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.ResponseStatus;
import org.springframework.web.bind.annotation.RestController;

/**
 * Auth endpoints: JWT register/login/refresh plus profile management.
 *
 * <p>Operation IDs match what drf-spectacular emits for the Django backend, which
 * keeps the generated frontend hook names identical across every backend.
 *
 * <p>Generated by Blacksmith. You own this file — customize as needed.
 */
@RestController
@RequestMapping("/api/auth")
@Tag(name = "auth")
public class AuthController {

    private final AuthService auth;

    public AuthController(AuthService auth) {
        this.auth = auth;
    }

    @PostMapping("/register/")
    @ResponseStatus(HttpStatus.CREATED)
    @Operation(operationId = "auth_register_create", summary = "Create a new user account. Returns JWT tokens.")
    public TokenPair register(@Valid @RequestBody RegisterRequest request) {
        return auth.register(request);
    }

    @PostMapping("/login/")
    @Operation(operationId = "auth_login_create", summary = "Authenticate with email and password.")
    public TokenPair login(@Valid @RequestBody LoginRequest request) {
        return auth.login(request);
    }

    @PostMapping("/refresh/")
    @Operation(operationId = "auth_refresh_create", summary = "Exchange a valid refresh token for a new token pair.")
    public TokenPair refresh(@Valid @RequestBody RefreshRequest request) {
        return auth.refresh(request.refresh());
    }

    @GetMapping("/me/")
    @Operation(operationId = "auth_me_retrieve", summary = "Get the current authenticated user profile.")
    public UserResponse me(@AuthenticationPrincipal User user) {
        return UserResponse.from(user);
    }

    @PatchMapping("/me/")
    @Operation(operationId = "auth_me_partial_update", summary = "Update the current authenticated user profile.")
    public UserResponse updateMe(@AuthenticationPrincipal User user, @RequestBody PatchedUserRequest request) {
        return UserResponse.from(auth.updateProfile(user, request));
    }

    @PostMapping("/change-password/")
    @Operation(operationId = "auth_change_password_create", summary = "Change the current user password.")
    public Detail changePassword(@AuthenticationPrincipal User user, @Valid @RequestBody ChangePasswordRequest request) {
        auth.changePassword(user, request);
        return new Detail("Password changed successfully.");
    }

    @PostMapping("/forgot-password/")
    @Operation(operationId = "auth_forgot_password_create", summary = "Request a password reset email.")
    public Detail forgotPassword(@Valid @RequestBody ForgotPasswordRequest request) {
        // TODO: send the reset email. Always answer the same, so the response
        // does not reveal which addresses have accounts.
        return new Detail("If an account exists, a reset email has been sent.");
    }

    @PostMapping("/reset-password/")
    @Operation(operationId = "auth_reset_password_create", summary = "Reset password using a token from the reset email.")
    public Detail resetPassword(@Valid @RequestBody ResetPasswordRequest request) {
        // TODO: verify the token and set the new password.
        return new Detail("Password has been reset successfully.");
    }

    /**
     * Tokens are stateless, so logging out means the client discards them; this
     * only confirms it. A token blacklist can be added here later.
     */
    @PostMapping("/logout/")
    @Operation(operationId = "auth_logout_create", summary = "Log out.")
    public Detail logout(@AuthenticationPrincipal User user, @Valid @RequestBody LogoutRequest request) {
        return new Detail("Successfully logged out.");
    }
}
